  private buildManifest(input: {
    auditPackageId: string;
    generatedAt: Date;
    generatedBy: { id: string; email: string; name: string };
    company: { id: string; name: string; rut: string | null };
    scope: AuditPackageManifest['scope'];
    files: Array<{ name: string; buffer: Buffer; rowsCount: number | null }>;
    snapshot: DataSnapshot;
    failedReports: Array<{ name: string; reason: string }>;
  }): AuditPackageManifest {
    const fileEntries: ManifestFileEntry[] = input.files.map((f) => ({
      name: f.name,
      sha256: this.computeHash(f.buffer),
      size: f.buffer.length,
      rowsCount: f.rowsCount,
    }));
    return {
      version: '1.0',
      auditPackageId: input.auditPackageId,
      generatedAt: input.generatedAt.toISOString(),
      generatedBy: input.generatedBy,
      company: input.company,
      scope: input.scope,
      files: fileEntries,
      packageSignature: this.computePackageSignature(fileEntries),
      dataSnapshot: input.snapshot,
      framework: LEGAL_FRAMEWORK_CHILE.map((l) => l.name),
      failedReports: input.failedReports,
    };
  }

  private async composeZip(
    coverPdf: Buffer,
    legalPdf: Buffer,
    manifest: AuditPackageManifest,
    reports: Array<{ name: string; buffer: Buffer }>,
  ): Promise<Buffer> {
    return new Promise<Buffer>((resolve, reject) => {
      const stream = new PassThrough();
      const chunks: Buffer[] = [];
      stream.on('data', (c: Buffer) => chunks.push(c));
      stream.on('end', () => resolve(Buffer.concat(chunks)));
      stream.on('error', reject);

      const archive = archiver('zip', { zlib: { level: 9 } });
      archive.on('error', reject);
      archive.pipe(stream);

      archive.append(coverPdf, { name: REPORT_FILES.COVER });
      archive.append(legalPdf, { name: REPORT_FILES.LEGAL });
      archive.append(JSON.stringify(manifest, null, 2), {
        name: REPORT_FILES.MANIFEST,
      });
      for (const r of reports) {
        archive.append(r.buffer, { name: r.name });
      }

      archive.finalize();
    });
  }

  private computeHash(buffer: Buffer): string {
    return createHash('sha256').update(buffer).digest('hex');
  }

  /* Master signature — SHA-256 of every file's hash concatenated.
     Stable regardless of file order because we sort by name first. */
  private computePackageSignature(files: ManifestFileEntry[]): string {
    const sorted = [...files].sort((a, b) => a.name.localeCompare(b.name));
    const concatenated = sorted.map((f) => f.sha256).join('');
    return createHash('sha256').update(concatenated).digest('hex');
  }
