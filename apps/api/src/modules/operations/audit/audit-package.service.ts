/* OPS-036 — orchestrates the audit-package generation:
   1. Run the 7 reports (4 from OPS-031, 3 new) — per-report
      try/catch so a single bad report doesn't kill the whole
      package; failed ones are flagged in the manifest and on
      the cover PDF.
   2. Render the cover PDF and the legal-framework PDF.
   3. Build the manifest JSON with SHA-256 of every file.
   4. ZIP everything with predictable filenames.
   5. Persist the row + bytes (MinIO when configured, DB blob
      fallback) and return the AuditPackage record. */

const AUDIT_PACKAGE_BUCKET = process.env.OPERATIONS_BUCKET || 'excelsia-documents';
const PACKAGE_TTL_DAYS = 365;

interface ReportProduce {
  /* Filename inside the ZIP, e.g. "01-cumplimiento-documental.xlsx". */
  fileName: string;
  /* Display label for the cover PDF and manifest. */
  label: string;
  /* Stable code referenced by the legal framework. */
  code: string;
  /* Generated bytes — null when generation failed. */
  buffer: Buffer | null;
  /* Error message captured when buffer is null. */
  error: string | null;
}

export interface ManifestFileEntry {
  name: string;
  sha256: string;
  size: number;
  rowsCount: number | null;
}

export interface AuditPackageManifest {
  version: '1.0';
  auditPackageId: string;
  generatedAt: string;
  generatedBy: { id: string; email: string; name: string };
  company: { id: string; name: string; rut: string | null };
  scope: {
    period: { from: string; to: string };
    locations: 'all' | string[];
    assetTypes: 'all' | string[];
    reason: string;
  };
  files: ManifestFileEntry[];
  packageSignature: string;
  dataSnapshot: DataSnapshot;
  framework: string[];
  failedReports: Array<{ name: string; reason: string }>;
}

export interface DataSnapshot {
  totalAssets: number;
  assetsWithCriticalIssues: number;
  totalDocuments: number;
  totalProcedures: number;
  totalPermits: number;
  totalActiveAlerts: number;
  complianceGlobalAtMoment: number;
}

export interface GeneratePackageInput {
  periodFrom: string;
  periodTo: string;
  locationIds?: string[];
  assetTypeIds?: string[];
  reason: string;
  /* Optional subset of report codes (REPORT_FILES.REPORTS[*].code). */
  includedReports?: string[];
}

export interface ValidationResult {
  valid: boolean;
  expectedFiles: number;
  actualFiles: number;
  hashMismatches: string[];
  missingFiles: string[];
  extraFiles: string[];
  packageSignatureMatches: boolean;
}

